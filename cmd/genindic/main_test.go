func TestMain2(t *testing.T) {
	srv := stubServer(map[string]string{"/isc": iscStub, "/ipc": ipcStub})
	defer srv.Close()
	out := filepath.Join(t.TempDir(), "m.go")

	origExit, origArgs := osExit, os.Args
	var code int
	osExit = func(c int) { code = c }
	os.Args = []string{"genindic", srv.URL + "/isc", srv.URL + "/ipc", out}
	defer func() { osExit, os.Args = origExit, origArgs }()

	main()
	if code != 0 {
		t.Errorf("main exit = %d, want 0", code)
	}
	if _, err := os.Stat(out); err != nil {
		t.Errorf("main did not write output: %v", err)
	}
}
